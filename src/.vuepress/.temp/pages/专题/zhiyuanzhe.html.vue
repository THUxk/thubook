<li>志愿服务认证时间累计达到<span style="font-weight:bold">20</span>小时，可获得<span style="font-weight:bold">“二星级紫荆志愿者”</span>称号。</li>
<li>志愿服务认证时间累计达到<span style="font-weight:bold">50</span>小时，可获得<span style="font-weight:bold">“三星级紫荆志愿者”</span>称号。</li>
<li>志愿服务认证时间累计达到<span style="font-weight:bold">120</span>小时，且至少参加过<span style="font-weight:bold">3次</span>不同的志愿项目，经审核后可获得<span style="font-weight:bold">“四星级紫荆志愿者”</span>称号。</li>
<li>志愿服务认证时间累计达到<span style="font-weight:bold">200</span>小时，且至少参加过<span style="font-weight:bold">5次</span>不同的志愿项目，经审核后可获得<span style="font-weight:bold">“五星级紫荆志愿者”</span>称号。</li>
</ul>
