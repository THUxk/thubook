<p>每年5月左右会进行清华星级志愿者的评选，评选标准基于<a href="http://www.bv2008.cn" target="_blank" rel="noopener noreferrer">志愿北京网站<ExternalLinkIcon/></a>上的志愿工时和项目数量，星级从低到高依次为一星到五星志愿者。具体规则如下（摘自“清华大学紫荆志愿者分级嘉许办法”）：</p>
