<h2 id="小学期" tabindex="-1"><a class="header-anchor" href="#小学期" aria-hidden="true">#</a> 小学期</h2>
<p>在暑假期间会用2-3周的时间集中上完一门课。这期间每天都只上那一门课。俗称小学期。</p>
<p>通常大一大二每个暑假可能会有2个小学期，一个2周，一个3周。具体时间可能在这学期结束，也可能在下学期开学前</p>
<h2 id="非清本" tabindex="-1"><a class="header-anchor" href="#非清本" aria-hidden="true">#</a> 非清本</h2>
<p>指本科不是清华的同学。通常含有学历歧视含义。<s>例如北京大学同学。</s></p>
<h2 id="书院相关" tabindex="-1"><a class="header-anchor" href="#书院相关" aria-hidden="true">#</a> 书院相关</h2>
<p>卷院/浅蓝书院：未央书院。前者顾名思义，后者因院徽得名。</p>
<p>非院：非清本收留院。通常指未央书院。一些对高考成绩耿耿于怀的同学用来歧视用的。</p>
<p>深蓝书院：行健书院。因院徽得名。</p>
<p>六边形书院：探微书院。因院徽得名。</p>
