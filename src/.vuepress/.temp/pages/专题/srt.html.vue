<li><strong>学生报名时间</strong>：10月13日至10月23日</li>
<li><strong>立项人集中审核学生报名时间</strong>：10月24日至10月28日</li>
</ul>
<h3 id="常见问题-faq" tabindex="-1"><a class="header-anchor" href="#常见问题-faq" aria-hidden="true">#</a> 常见问题 (FAQ)</h3>
<ol>
<li><strong>教师参与SRT计划立项申请要求</strong>：中级及以上职称的在校教师可申请立项。</li>
<li><strong>学生参与SRT计划立项申请要求</strong>：一～三年级的本科生可申请立项，不对研究生开放。</li>
<li><strong>立项申请时间</strong>：每学年秋季、春季学期开学初各一次。</li>
<li><strong>立项申请程序</strong>：登录 <a href="http://info.tsinghua.edu.cn/" target="_blank" rel="noopener noreferrer">info<ExternalLinkIcon/></a>，在教学--SRT栏目下填写立项申请表并确认提交。学生需请指导教师审核。</li>
<li><strong>每次可申报项目数</strong>：同一批次最多可申请2个项目。</li>
<li><strong>每次可接纳学生数</strong>：建议接纳人数为3-5人。</li>
<li><strong>项目学分</strong>：项目学分为1-3，执行时间为半年的最高2学分，一年的最高3学分。</li>
<li><strong>项目执行时间</strong>：一般为半年至一年。</li>
<li><strong>立项审批程序</strong>：教务处汇总项目基本信息并组织各院系SRT计划指导组专家审核，审批通过的项目将在网上开放学生报名。</li>
<li><strong>报名申请时间</strong>：每学年秋季、春季学期第5-6周。</li>
<li><strong>报名申请程序</strong>：学生登录 <a href="http://info.tsinghua.edu.cn/" target="_blank" rel="noopener noreferrer">info<ExternalLinkIcon/></a>，在“学习-SRT(新版)-学生报名-查看可以报名的项目”栏目下查询并报名。</li>
<li><strong>接纳学生报名程序</strong>：立项人同意接收后报名成立，被接收的学生直到项目结题或教师批准项目终止后方可再报名参加其他项目。</li>
<li><strong>错过报名怎么办</strong>：可参加下一次报名。</li>
<li><strong>立项启动程序</strong>：已接收学生报名的项目自接收之日起启动。</li>
<li><strong>经费申请程序</strong>：填写SRT计划立项申请表时可提出项目经费申请，金额不超过5000元。</li>
<li><strong>经费审批及下拨</strong>：教务处统一规划和管理，在春季学期3月及6月下拨项目经费。学生立项项目经费由指导教师代管。</li>
<li><strong>项目结题程序</strong>：学生须向导师提交完整的书面结题报告，同时上网填写项目成果和项目体会，指导教师给出成绩及学分。</li>
<li><strong>SRT计划可取代其他实践教学环节吗</strong>：学生可要求取代综合论文训练，须向所在院系提出申请并参加结题答辩。</li>
<li><strong>SRT计划优秀项目评选与奖励</strong>：每学年秋季学期11月开展评优工作，对表现突出的项目及其参与者和指导教师进行奖励，并对组织工作成绩突出的院系实行奖励。</li>
</ol>
