<template><div><h1 id="srt-项目指南" tabindex="-1"><a class="header-anchor" href="#srt-项目指南" aria-hidden="true">#</a> SRT 项目指南</h1>
<p>Student Research Training,简称SRT,是大多数本科生参与科研的一种方式。</p>
<p>每学期初会有 SRT 项目的立项与报名，请及时关注 info 以及院系通知群。立项和报名顺序是先学生立项，然后学生报名。SRT 系统在 info-学习栏中，“已立项”代表教师已立项但没有学生报名，“报名中”代表已有学生报名。推荐同学在报名之后（或之前）尽快向老师发邮件沟通。</p>
<h2 id="srt-系统使用指南" tabindex="-1"><a class="header-anchor" href="#srt-系统使用指南" aria-hidden="true">#</a> SRT 系统使用指南</h2>
<h3 id="立项申请" tabindex="-1"><a class="header-anchor" href="#立项申请" aria-hidden="true">#</a> 立项申请</h3>
<ol>
<li>首页点击“立项申请”，按要求填写立项申请书，带“*”为必填项，然后点击“提交”按钮提交申请书，或点击“暂存”按钮将所填信息暂存。</li>
<li>暂存信息在当前项目-本人立项的项目页面，点击“确认”提交立项申请书，点击“删除”则删除立项申请，点击“查看/修改申请书”修改项目信息。</li>
<li>每个暂存的立项申请必须确认后才能进行后续的立项审核。</li>
<li>确认申请后，点击“查看申请书”浏览所填写的全部内容。</li>
</ol>
<h3 id="学生报名" tabindex="-1"><a class="header-anchor" href="#学生报名" aria-hidden="true">#</a> 学生报名</h3>
<ol>
<li>首页点击“学生报名”，查看当前批次报名的项目，点击“查看可以报名的项目”进入可报名项目列表。</li>
<li>按检索条件查询项目，点击项目名称查看项目申请书内容，点击“填写申请书”进行报名。</li>
<li>填好报名申请书后，点击“提交”确认申请，点击“暂存”则将所填信息暂存。</li>
<li>暂存后在已报名的项目页面，点击“查看/修改”按钮修改报名信息，点击“确认”确认报名，点击“删除”删除报名申请。</li>
<li>报名阶段结束后未确认的报名申请书自动作废。</li>
<li>报名后可在当前项目-本人参加的项目页面查看报名审核信息。</li>
</ol>
<h3 id="报名审核" tabindex="-1"><a class="header-anchor" href="#报名审核" aria-hidden="true">#</a> 报名审核</h3>
<ol>
<li>首页点击“报名审核”进入当前项目页面，选择“本人立项的项目”选项卡，如果项目最终审核通过并有人报名，点击“查看报名情况/报名审核”进行报名审核。</li>
<li>对于未审核的学生，点击“填写”进行报名审核。提交后不能修改。</li>
<li>立项人在报名审核阶段可以设置“是否接收报名”，选择“是”接收报名，选择“否”停止接收报名，学生在可报名的项目列表中看不到该项目。</li>
</ol>
<h3 id="项目结题" tabindex="-1"><a class="header-anchor" href="#项目结题" aria-hidden="true">#</a> 项目结题</h3>
<ol>
<li>结题顺序为学生先结题，教师后结题。</li>
<li>学生为立项人时，首页点击“项目结题”，找到需要结题的项目，点击“项目结题”，在立项人结题项点击“填写”，为每个参与学生填写立项人评语，再点击“填写立项人体会及建议成果”进行个人结题。</li>
<li>学生为参与者时，首页点击“项目结题”，找到需要结题的项目，点击“项目结题”进行个人结题。</li>
<li>结题后的项目在结题项目页面可以查看，点击“项目结题”查看立项人评语、教师评语、成绩等信息。</li>
</ol>
<h3 id="重要时间" tabindex="-1"><a class="header-anchor" href="#重要时间" aria-hidden="true">#</a> 重要时间</h3>
