<h2 id="上课" tabindex="-1"><a class="header-anchor" href="#上课" aria-hidden="true">#</a> 上课</h2>
<p>大学上课和高中也不一样。同一门课，每个老师的上课时间和上课地点都不尽相同。比如微积分A，甲老师可能每周一早上8点到10点在X教学楼的S1教室上课，乙老师可能每周三10点到12点在Y教学楼的M3教室上课。所以大学上课需要自己在规定的时间进入指定的教室等老师来。众所周知，清华一是学校大，二是课间短。可能上一节课微积分在三教，下一节课制造工程体验就在李兆基，所以下课后需要飞奔去另一个教学楼赶去上课。</p>
<h2 id="抽签" tabindex="-1"><a class="header-anchor" href="#抽签" aria-hidden="true">#</a> 抽签</h2>
<p>由于同一门课可能有超过课容量的同学选择，所以会先进行志愿抽签，志愿优先级：</p>
<p>必修一 &gt; 必修二 &gt; 必修三 &gt; 限选一 &gt; 限选二 &gt; 限选三 &gt; 任选优先  &gt; 任选一 &gt; 任选二 &gt; 任选三</p>
<p>只有高优先级的全部抽完，才会在下一优先级中抽取。</p>
<p>未抽中的同学，会随机进入wl（waiting list）等待候补。（如果已经选中的同学退课，则候补队列中的同学自动补上）</p>
<h2 id="防沉迷机制" tabindex="-1"><a class="header-anchor" href="#防沉迷机制" aria-hidden="true">#</a> 防沉迷机制</h2>
<p>为了防止大家沉迷学习，学校规定选课每学期除体育和重修外，大一不超过26学分，大二大三不超过30学分。如想解除防沉迷限制，需申请特批学分，审批通过后才可选课。</p>
