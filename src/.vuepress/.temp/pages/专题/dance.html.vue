<template><div><h1 id="新生舞会" tabindex="-1"><a class="header-anchor" href="#新生舞会" aria-hidden="true">#</a> 新生舞会</h1>
<p>新生舞会是新生最感兴趣的话题之一，因为他听上去最“有趣”！</p>
<p>下面对新生舞会相关问题做以解释：</p>
<ul>
<li>
<p><span style = "font-weight:bold">新生舞会是全体新生都要参加吗？</span></p>
<p>新生舞会由各个院系自行举办，<span style = "font-weight:bold">并没有统一组织的校级活动</span>。通常由各院系学生会自己决定时间，地点进行举办。常见的做法也有几个院系联合举办，甚至联合其他学校的新生（如人大）一起举办。例如<a href="https://mp.weixin.qq.com/s/7esKphedFrYo41bHStYHbg" target="_blank" rel="noopener noreferrer">两校八系新生舞会<ExternalLinkIcon/></a></p>
</li>
<li>
<p><span style = "font-weight:bold">新生舞会的时间一般在什么时候？</span></p>
<p>由于新生舞会并不是统一举办，所以每个院系举办的时间不一致，<span style="font-weight:bold">可能在开学前两周，也可能在10月，11月份，期中考试之后</span>。总之是各院系自己决定的。</p>
</li>
<li>
<p><span style = "font-weight:bold">新生舞会需要准备西装吗？</span></p>
<p><span style = "font-weight:bold">需要</span>。新生一般要求男生穿着正装，女生要求穿着晚礼服。</p>
</li>
<li>
<p><span style = "font-weight:bold">不会跳舞怎么办？</span></p>
<p>一般在刚开学前1-2周，各院系会组织免费的舞蹈培训，可以参见这个舞蹈培训学习基本的舞蹈姿势。</p>
</li>
<li>
<p><span style = "font-weight:bold">对舞蹈不感兴趣，可以不去吗？</span></p>
<p><span style = "font-weight:bold">可以</span>。新生舞会并不强制参加，不感兴趣可以不去。新生舞会的目的也只是促进新生互相认识，破冰，不去参加对之后并没有什么影响。</p>
</li>
<li>
<p><span style = "font-weight:bold">新生舞会的舞伴怎么找？学校包分配吗？</span></p>
<p>新生舞会的舞伴通常需要自己提前寻找，院系通常不负责分配舞伴。舞伴可以是同院系的新生，也可以是北京其他高校的同学，甚至无所谓是新生，只要能来参加就行。</p>
</li>
<li>
<p><span style = "font-weight:bold">新生舞会除了跳舞还干什么？</span></p>
<p>还有其他有趣的集体活动如击鼓传花，你画我猜等，跳舞只是一个环节。当然也有丰富的零食饮料，可以去白嫖。</p>
</li>
</ul>
