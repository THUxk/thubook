<li>建议公开往年报录情况，避免盲投博弈。</li>
</ul>
</li>
</ol>
<h2 id="其他注意事项" tabindex="-1"><a class="header-anchor" href="#其他注意事项" aria-hidden="true">#</a> 其他注意事项</h2>
