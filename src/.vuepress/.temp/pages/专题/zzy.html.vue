</ul>
</li>
<li>
<p><span style = "font-weight:bold">课程</span>：</p>
<ul>
<li>部分院系对转入学生的课程要求较高，可能会安排降级（如交叉信息院、医学实验班）。</li>
<li>提前修读相关课程有助于减轻转入后的负担。</li>
</ul>
</li>
<li>
<p><span style = "font-weight:bold">其他</span>：</p>
<ul>
<li>高考成绩可能作为参考，但具体作用不详。</li>
</ul>
</li>
</ol>
